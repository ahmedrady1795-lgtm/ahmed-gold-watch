import assert from 'node:assert/strict';
import {observeBtcOpening,validBtcOpeningCall,btcMemoryTick,btcOpeningSummary,BTC_OPENING_VERSION} from '../lib/btc-opening-memory.ts';
import {mergeBtcMarketMemory,mergeMarketMemory,settleMarketMemory} from '../lib/gold-market-memory.ts';
const target=Date.parse('2026-11-27T05:10:00Z'),now=target-10000,source='Kraken XBT/USD · fresh-candle fallback';
const bars=Array.from({length:24},(_,i)=>{const p=60000+i*2;return {time:target-(25-i)*60000,open:p,close:p+1,high:p+5,low:p-5};});
const chart={fresh:true,candleSource:source,chartCandles:bars};
const tape={ok:true,status:'LIVE_SAMPLE',source:'Kraken XBT/USD',fetchedAt:now-100,latestTrade:{at:now-500,price:60048},shortPressure:{asOf:now-500,from:now-6000,trades:30,deltaPct:60,priorDeltaPct:30,low:60046,high:60049,firstPrice:60046,lastPrice:60048}};
const prior={at:now-3000,price:60047,source:tape.source};
const row=observeBtcOpening(now,chart,null,tape,prior);
assert.ok(row);assert.equal(row.target,target);assert.equal(row.flowSources,1);
assert.equal(row.outcome,'PENDING');assert.equal(row.spread,null);
assert.equal(btcMemoryTick(source,{...tape,source:'Coinbase Exchange BTC-USD'},now),null);
assert.equal(observeBtcOpening(now,chart,null,{...tape,latestTrade:{at:now-15000,price:60048}},prior),null);
assert.deepEqual(observeBtcOpening(now,{...chart,chartCandles:[...bars,{time:target,open:60000,close:65000,high:66000,low:59000}]},null,tape,prior),row);
assert.equal(observeBtcOpening(now,{...chart,chartCandles:bars.filter((_,i)=>i!==8)},null,tape,prior),null);
const call={version:BTC_OPENING_VERSION,target,issued:now,side:'BUY',reason:'test',source,quoteSource:tape.source,quoteAt:now-500,priceAt:60048};
assert.equal(validBtcOpeningCall(call,now),true);
assert.equal(validBtcOpeningCall({...call,issued:target},target),false);
assert.equal(validBtcOpeningCall({...call,quoteSource:'Coinbase Exchange BTC-USD'},now),false);
const pending={...row,candidate:call,published:true};
const future=Array.from({length:5},(_,i)=>({time:target+i*60000,open:60050+i*5,close:60054+i*5,high:60056+i*5,low:60049+i*5}));
const settled=settleMarketMemory([pending],target+303000,source,future)[0];
assert.equal(settled.outcome,'SETTLED');assert.equal(settled.candidate.side,'BUY');
assert.equal(btcOpeningSummary([settled],target+303000).quality.hits,1);
assert.equal(btcOpeningSummary([{...settled,published:false}],target+303000).quality.issued,0);
assert.equal(btcOpeningSummary([{...settled,published:false}],target+303000).withheldResearch.hits,1);
assert.equal(mergeMarketMemory(target+303000,[settled]).length,0);
assert.deepEqual(mergeBtcMarketMemory(target+303000,[pending],[settled]),[settled]);
console.log('PASS: server BTC pre-opening memory, same-venue prints, future-only grade, no cross-asset archives, published/withheld isolation');
