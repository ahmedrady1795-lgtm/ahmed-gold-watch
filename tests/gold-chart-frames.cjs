const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript'),vm=require('node:vm');
const m={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/gold-chart-frames.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,{module:m,exports:m.exports});
const {aggregateGoldBars,recoverGoldFrames}=m.exports;
const now=Date.parse('2026-11-24T06:00:00Z');
const rows=Array.from({length:180},(_,i)=>({time:now-(180-i)*60000,open:3600+i/10,high:3601+i/10,low:3599+i/10,close:3600.3+i/10}));
const first=aggregateGoldBars(rows,60000,300000,now);
assert.equal(first.length,36);
assert.equal(first[0].open,rows[0].open);
assert.equal(first[0].close,rows[4].close);
assert.equal(first[0].high,rows[4].high);
assert.equal(first[0].low,rows[0].low);
assert.equal(aggregateGoldBars(rows.filter((_,i)=>i!==2),60000,300000,now).length,35,'a missing minute must never manufacture a five-minute candle');
const full=recoverGoldFrames({c1:rows,c5:[],c15:[],c60:[]},now);
assert.equal(full.c5.length,36);
assert.equal(full.c15.length,12);
assert.equal(full.c60.length,3);
const native={...first[0],high:first[0].high+2};
assert.equal(recoverGoldFrames({c1:rows,c5:[native],c15:[],c60:[]},now).c5[0].high,native.high,'source-supplied closed bars retain precedence');
const m5Only=recoverGoldFrames({c1:[],c5:first,c15:[],c60:[]},now);
assert.equal(m5Only.c1.length,0,'never infer individual minutes from higher frames');
assert.equal(m5Only.c5.length,36);
assert.equal(m5Only.c15.length,12);
assert.equal(m5Only.c60.length,3);
assert.equal(recoverGoldFrames({c1:[{...rows[0],time:now}],c5:[],c15:[],c60:[]},now).c1.length,0);
console.log('PASS: exact same-source closed OHLC aggregation, missing intervals and partial M5 fallback');
