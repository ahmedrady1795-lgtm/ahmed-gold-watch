const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const exports_={};vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/news-adp-pulse.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,{exports:exports_,URL,Intl});
const {adpReleaseLinks,parseAdpRelease,verifiedAdpToday,mergeAdpEvents}=exports_;
const time=Date.parse('2026-11-24T13:15:00Z');
assert.equal(verifiedAdpToday(time-1)[0].actual,'');
assert.equal(verifiedAdpToday(time)[0].actual,'21K');
const url='https://mediacenter.adp.com/2026-11-24-ADP-National-Employment-Report-Preliminary-Estimate-for-November-7';
assert.equal(adpReleaseLinks('<a href="'+url+'">report</a>')[0],url);
const html='<p>U.S. private employers added an average of <b>21,000</b> jobs per week, according to the NER Pulse.</p><p>The next NER Pulse will be released December 1, 2026.</p>';
assert.equal(parseAdpRelease(url,html,time-1),null);
const release=parseAdpRelease(url,html,time);
assert.equal(release.event.actual,'21K');
assert.equal(release.event.time,time);
assert.equal(release.next.time,Date.parse('2026-12-01T13:15:00Z'));
assert.equal(release.next.actual,'');
const events=[{...release.event,name:'ADP Employment Change Weekly',actual:'',forecast:'',previous:'23.8K'}];
mergeAdpEvents(events,verifiedAdpToday(time),time);
assert.equal(events.length,1);
assert.equal(events[0].actual,'21K');
assert.equal(events[0].forecast,'');
console.log('PASS: verified ADP release, no lookahead, official source parser and deduplication');
