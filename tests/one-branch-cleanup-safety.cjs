const assert=require('node:assert/strict');
const fs=require('node:fs');
const workflow=fs.readFileSync('.github/workflows/one-branch-cleanup.yml','utf8');
const code=fs.readFileSync('scripts/one-branch-cleanup.mjs','utf8');
assert.match(workflow,/workflow_dispatch:/);
assert.match(workflow,/inputs\.confirmation == 'DELETE_ALL_OTHER_BRANCHES'/);
assert.match(workflow,/permissions:\s*\n\s*contents: write/);
assert.match(workflow,/fetch-depth: 0/);
assert.match(workflow,/git bundle create/);
assert.match(workflow,/git bundle verify/);
assert.match(workflow,/actions\/upload-artifact@v4/);
assert.match(workflow,/run: node scripts\/one-branch-cleanup\.mjs/);
assert.match(code,/metadata\.default_branch!=='render-free'/);
assert.match(code,/QANNAS_BRANCH_CLEANUP_BUNDLE_VERIFIED/);
assert.match(code,/current\.savedAt|legacy\.savedAt>current\.savedAt/);
assert.match(code,/if\(b\.protected\)/);
assert.match(code,/git\/ref\/heads\//);
assert.match(code,/git\/refs\/heads\//);
assert.match(code,/if\(ref\?\.object\?\.sha!==b\.commit\.sha\)/);
assert.match(code,/b\.name!=='render-free'/);
assert.match(code,/remaining\.length!==1\|\|remaining\[0\]!=='render-free'/);
console.log('PASS: no branch cleanup without default switch, checked archives and a verified Git bundle');
