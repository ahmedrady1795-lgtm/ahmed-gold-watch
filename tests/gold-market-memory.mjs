import assert from 'node:assert/strict';
import {captureMarketMemory,settleMarketMemory,mergeMarketMemory,marketMemoryReport} from '../lib/gold-market-memory.ts';
const target=Date.parse('2026-11-26T19:35:00Z'),now=target-20000;
const source='Biquote · MT5 XAUUSD candles';
const bars=Array.from({length:16},(_,i)=>{const p=3500+i*.1;return {time:target-(17-i)*60000,open:p,close:p+.05,high:p+.1,low:p-.1};});
const q={ok:true,status:'live',source:'Biquote · MT5 XAUUSD',price:3501.6,bid:3501.58,ask:3501.62,sourceTime:now-1000,fetchedAt:now};
const flow={asOf:now-1000,sources:['Bybit XAUUSDT perpetual','OKX XAUUSDT perpetual'],strongSide:'BUY',delta:40,fastBuyPct:80};
const snap=captureMarketMemory(now,source,bars,q,flow);
assert.ok(snap);assert.equal(snap.target,target);assert.equal(snap.outcome,'PENDING');assert.equal(snap.flowSources,2);
assert.equal(captureMarketMemory(now,source,bars,{...q,sourceTime:now-15000},flow),null);
assert.equal(captureMarketMemory(now,source,bars.filter((_,i)=>i!==8),q,flow),null);
assert.deepEqual(captureMarketMemory(now,source,[...bars,{time:target,open:3500,close:4000,high:4100,low:3400}],q,flow),snap);
assert.equal(captureMarketMemory(now,source,bars,q,{...flow,asOf:now-15000}).flowDelta,null);
const future=Array.from({length:5},(_,i)=>({time:target+i*60000,open:3500+i*.1,close:3500+i*.1+.05,high:3500+i*.1+.11,low:3499.95+i*.1}));
assert.equal(settleMarketMemory([snap],target+60000,source,future)[0].outcome,'PENDING');
const settled=settleMarketMemory([snap],target+303000,source,future)[0];
assert.equal(settled.outcome,'SETTLED');assert.equal(settled.direction,'BUY');assert.equal(settled.firstThreshold,'BUY');
assert.equal(settleMarketMemory([snap],target+303000,'foreign',future)[0].outcome,'PENDING');
assert.equal(settleMarketMemory([snap],target+900000,source,future.slice(1))[0].outcome,'UNKNOWN');
const both=[{...future[0],high:3501,low:3499},...future.slice(1)];
assert.equal(settleMarketMemory([snap],target+303000,source,both)[0].firstThreshold,'AMBIGUOUS');
assert.deepEqual(mergeMarketMemory(target+303000,[snap],[settled]),[settled]);
assert.deepEqual(mergeMarketMemory(target+303000,[snap],[{...settled,mid:1}]),[snap]);
assert.equal(marketMemoryReport([settled]).settled,1);
console.log('PASS: market memory captures no-signal windows, past-only data, source integrity, ambiguous excursions and immutable checkpoint');
