import assert from 'node:assert/strict';
import {parseGoldStream,retainGoldStream} from '../lib/gold-perp-stream.ts';
import {chooseGoldM1Baseline} from '../lib/gold-m1-paired-selector.ts';
const now=1800000000000;
const by={topic:'publicTrade.XAUUSDT',data:[{s:'XAUUSDT',i:'a',T:now-1000,p:'3500',v:'2',S:'Buy'}]};
const ok={arg:{channel:'trades',instId:'XAU-USDT-SWAP'},data:[{instId:'XAU-USDT-SWAP',tradeId:'b',ts:String(now-500),px:'3500',sz:'3',side:'sell'}]};
assert.deepEqual(parseGoldStream('bybit',by,now),[{id:'a',at:now-1000,price:3500,qty:2,buy:true}]);
assert.equal(parseGoldStream('okx',ok,now)[0].buy,false);
assert.equal(parseGoldStream('bybit',{...by,topic:'publicTrade.BTCUSDT'},now).length,0);
assert.equal(parseGoldStream('bybit',{...by,data:[{...by.data[0],BT:true}]},now).length,0);
assert.equal(parseGoldStream('okx',{...ok,data:[{...ok.data[0],ts:String(now+1)}]},now).length,0);
assert.equal(parseGoldStream('okx',ok,now+31000).length,0);
const cache=new Map(),rows=parseGoldStream('bybit',by,now);
retainGoldStream(cache,rows,now);retainGoldStream(cache,rows,now);
assert.equal(cache.size,1);
retainGoldStream(cache,[],now+61000);assert.equal(cache.size,0);
const history=Array.from({length:50},(_,i)=>{const at=now-(i+2)*60000;return {id:at,issuedAt:at,chartSource:'XAUUSD',marketRegime:'RANGE',originalSide:'SELL',baselineSide:'BUY',directionObserved:i<35?'BUY':'SELL',directionEvaluatedAt:at+61000};});
const input={history,issuedAt:now,source:'XAUUSD',regime:'RANGE',baseline:'BUY',proposed:'SELL'};
assert.equal(chooseGoldM1Baseline(input).side,'BUY');
assert.equal(chooseGoldM1Baseline(input).tradeAuthorized,false);
assert.equal(chooseGoldM1Baseline({...input,history:history.slice(0,15)}).side,'SELL');
assert.equal(chooseGoldM1Baseline({...input,source:'BTC'}).side,'SELL');
assert.equal(chooseGoldM1Baseline({...input,regime:'LOW_ACTIVITY'}).side,'SELL');
assert.equal(chooseGoldM1Baseline({...input,history:history.map(r=>({...r,directionEvaluatedAt:now+1}))}).side,'SELL');
assert.equal(chooseGoldM1Baseline({...input,history:Array(50).fill(history[0])}).side,'SELL');
assert.equal(chooseGoldM1Baseline({...input,history:history.map((r,i)=>({...r,marketRegime:i>=35?'TREND':'RANGE'})),regime:'TREND'}).side,'SELL');
console.log('PASS: public XAU streaming parser, strict timestamps, duplicate/expiry guards and paired GOLD M1 past-only selector');
